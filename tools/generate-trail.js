// Generates the daily Word Trail grids (4x4). Usage: node tools/generate-trail.js [days=730] [seed]
// Writes trail-daily.js. Daily No. 1 is 16 Oct 2026.
'use strict';
const fs = require('fs'), path = require('path');
global.window = {}; require('../trailwords.js');
const T = require('../trail-core.js');
const days = +(process.argv[2] || 730), seed = +(process.argv[3] || 20261016);
const dict = T.decode(window.TRAIL_WORDS), rand = T.mulberry(seed), seen = new Set(), grids = [];
const t0 = Date.now(); let attempts = 0;
while (grids.length < days) {
  const r = T.generate(4, dict, rand); attempts += r.attempts;
  if (seen.has(r.grid)) continue; seen.add(r.grid); grids.push(r.grid);
}
fs.writeFileSync(path.join(__dirname, '..', 'trail-daily.js'),
  `// ${days} daily Word Trail grids (16 letters each, row by row). No. 1 = 16 Oct 2026. Generated by tools/generate-trail.js\nwindow.TRAIL_DAILY = "${grids.join('')}";\n`);
console.log(`${days} grids in ${((Date.now() - t0) / 1000).toFixed(1)}s, ${attempts} random grids tried`);
