// Usage: node tools/generate-sudoku.js <easy> <medium> <hard> <expert> [seed]
// Writes puzzles.js next to the games. Every puzzle has exactly one solution and is rated by the techniques it needs.
'use strict';
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const path = require('path'), fs = require('fs'), os = require('os');
const lib = require('./sudoku-lib');
const NAMES = ['', 'easy', 'medium', 'hard', 'expert'];

if (isMainThread) {
  const want = process.argv.slice(2, 6).map(Number); const seed = Number(process.argv[6] || 20261013);
  const threads = Math.max(1, os.cpus().length), out = { 1: new Set(), 2: new Set(), 3: new Set(), 4: new Set() };
  let done = 0; const t0 = Date.now();
  for (let t = 0; t < threads; t++) {
    const w = new Worker(__filename, { workerData: { seed: seed + t * 7919, want } });
    w.on('message', ({ level, s }) => {
      if (out[level].size < want[level - 1]) out[level].add(s);
      if ([1, 2, 3, 4].every(l => out[l].size >= want[l - 1])) finish();
    });
  }
  const tick = setInterval(() => console.error(`${((Date.now() - t0) / 1000) | 0}s`, [1, 2, 3, 4].map(l => `${NAMES[l]} ${out[l].size}/${want[l - 1]}`).join('  ')), 10000);
  function finish() {
    if (done++) return; clearInterval(tick);
    const body = [1, 2, 3, 4].map(l => `  ${NAMES[l]}: "${[...out[l]].join('')}"`).join(',\n');
    const file = path.join(__dirname, '..', 'puzzles.js');
    fs.writeFileSync(file, `// ${[1,2,3,4].map(l => out[l].size + ' ' + NAMES[l]).join(', ')} Sudoku puzzles. 81 digits each, 0 = blank. Generated by tools/generate-sudoku.js\nwindow.SUDOKU_PUZZLES = {\n${body}\n};\n`);
    console.error('wrote', file, ((Date.now() - t0) / 1000) | 0, 's'); process.exit(0);
  }
} else {
  const rand = lib.mulberry(workerData.seed), want = workerData.want;
  const have = [0, 0, 0, 0, 0];
  for (;;) {
    // Pick the level that is furthest behind, relative to its target.
    let target = 1, worst = 2;
    for (let l = 1; l <= 4; l++) { const r = have[l] / Math.max(1, want[l - 1]); if (r < worst) { worst = r; target = l; } }
    const res = lib.generate(target, rand);
    if (res) { have[res.level]++; parentPort.postMessage({ level: res.level, s: res.grid.join('') }); }
  }
}
