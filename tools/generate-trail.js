// Generates the daily Tendril grids and checks them against the rules.
//   node tools/generate-trail.js            generate and write trail-daily.js
//   node tools/generate-trail.js --check    only check the grids already in trail-daily.js
// Daily No. 1 = 16 Oct 2026 (day index 0). Small = 4x4 (window.TRAIL_DAILY, 16 letters a day), Big = 5x5
// (window.TRAIL_DAILY_BIG, 25 letters a day), 730 days each.
// Small grids for days 0..FROZEN stay exactly as they were published (they predate the current Small rule and may have
// more counted words than it allows); they are read from the existing trail-daily.js. From FROZEN+1 on, Small grids are
// generated with the SMALL rule, and Big grids are generated for every day. Seeded, so re-running with the same
// dictionary gives the same file; re-run it whenever trailwords.js changes (the counted words may change).
'use strict';
const fs = require('fs'), path = require('path');
const FROZEN = 42;          // last day index whose Small grid is kept as published (No. 43, 27 Nov 2026)
const DAYS = 730, SEED_SMALL = 20261127, SEED_BIG = 20261128;
const file = path.join(__dirname, '..', 'trail-daily.js');
const read = () => { global.window = {}; delete require.cache[file]; require(file); return { small: window.TRAIL_DAILY.match(/.{16}/g), big: (window.TRAIL_DAILY_BIG || '').match(/.{25}/g) || [] }; };
global.window = {}; require('../trailwords.js');
const T = require('../trail-core.js');
const dict = T.decode(window.TRAIL_WORDS);
const stat = a => a.length ? `avg ${(a.reduce((x, y) => x + y, 0) / a.length).toFixed(1)}, min ${Math.min(...a)}, max ${Math.max(...a)}` : 'none';

function verify(small, big) {
  let bad = 0; const sc = [], bc = [], frozenCounts = [];
  if (small.length !== DAYS || big.length !== DAYS) { console.log(`wrong lengths: small ${small.length}, big ${big.length}`); bad++; }
  small.forEach((g, i) => { const r = T.check(g, dict, 'small'); (i <= FROZEN ? frozenCounts : sc).push(r.targets); if (!r.ok && i > FROZEN) { bad++; console.log(`Small day ${i}: ${g} ${r.problems.join(', ')}`); } });
  big.forEach((g, i) => { const r = T.check(g, dict, 'big'); bc.push(r.targets); if (!r.ok) { bad++; console.log(`Big day ${i}: ${g} ${r.problems.join(', ')}`); } });
  const dup = a => a.length - new Set(a).size;
  console.log(`Small days 0-${FROZEN} (kept as published): counted words ${stat(frozenCounts)}`);
  console.log(`Small days ${FROZEN + 1}-${DAYS - 1}: counted words ${stat(sc)}`);
  console.log(`Big days 0-${DAYS - 1}: counted words ${stat(bc)}`);
  console.log(`duplicates: small ${dup(small)}, big ${dup(big)}`);
  console.log(bad ? `${bad} problem(s)` : 'all grids meet their rule');
  return !bad;
}

if (process.argv.includes('--check')) { const d = read(); process.exit(verify(d.small, d.big) ? 0 : 1); }

const old = read().small, t0 = Date.now();
const small = old.slice(0, FROZEN + 1), seen = new Set(small), big = [], seenBig = new Set();
let tries = 0;
const randS = T.mulberry(SEED_SMALL), randB = T.mulberry(SEED_BIG);
while (small.length < DAYS) { const r = T.generate('small', dict, randS); tries += r.attempts; if (seen.has(r.grid)) continue; seen.add(r.grid); small.push(r.grid); }
const t1 = Date.now();
while (big.length < DAYS) { const r = T.generate('big', dict, randB); tries += r.attempts; if (seenBig.has(r.grid)) continue; seenBig.add(r.grid); big.push(r.grid); }
const t2 = Date.now();
fs.writeFileSync(file,
  `// ${DAYS} daily Tendril grids per size, row by row, from day index 0 = No. 1 = 16 Oct 2026. Generated by tools/generate-trail.js\n` +
  `// Small: 4x4, 16 letters a day (days 0-${FROZEN} are the grids as first published).\nwindow.TRAIL_DAILY = "${small.join('')}";\n` +
  `// Big: 5x5, 25 letters a day.\nwindow.TRAIL_DAILY_BIG = "${big.join('')}";\n`);
console.log(`generated ${DAYS - FROZEN - 1} Small in ${((t1 - t0) / 1000).toFixed(1)}s and ${DAYS} Big in ${((t2 - t1) / 1000).toFixed(1)}s (${tries} random grids tried)`);
process.exit(verify(small, big) ? 0 : 1);
