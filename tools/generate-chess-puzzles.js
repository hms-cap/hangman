// Mines chess puzzles from engine self-play, the way online puzzle sites do:
// play games between weaker levels (so real blunders happen), stop right after a blunder,
// and keep positions where one move clearly wins. Mates are verified with an exact solver.
// Usage: node tools/generate-chess-puzzles.js [target=600] [out=chess-puzzles.js]
'use strict';
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const os = require('os'), fs = require('fs'), path = require('path');
const C = require('../chess-core.js');
const { Position, Engine, MATE } = C;
const VAL = [0, 100, 300, 320, 500, 900, 0];

const QUOTA = { mateIn1: 0.22, mateIn2: 0.32, mateIn3: 0.16, material: 0.30 };

if (isMainThread) {
  const target = +(process.argv[2] || 600), out = process.argv[3] || path.join(__dirname, '..', 'chess-puzzles.js');
  const want = Object.fromEntries(Object.entries(QUOTA).map(([k, f]) => [k, Math.round(target * f)]));
  const got = { mateIn1: [], mateIn2: [], mateIn3: [], material: [] }, seen = new Set(), t0 = Date.now();
  const threads = Math.max(1, os.cpus().length);
  const workers = [];
  const done = () => Object.keys(want).every(k => got[k].length >= want[k]);
  const report = () => console.log(`[${((Date.now() - t0) / 60000).toFixed(1)} min] ` + Object.keys(want).map(k => `${k} ${got[k].length}/${want[k]}`).join('  '));
  let timer = setInterval(report, 30000);
  for (let t = 0; t < threads; t++) {
    const w = new Worker(__filename, { workerData: { seed: t } }); workers.push(w);
    w.on('message', p => {
      if (p.why){ console.log('worker', t, JSON.stringify(p.why)); return; }
      const key = p.fen.split(' ').slice(0, 2).join(' ');
      if (seen.has(key) || got[p.kind].length >= want[p.kind]) return;
      seen.add(key); got[p.kind].push(p);
      if (done()) finish();
    });
  }
  function finish() {
    clearInterval(timer); report();
    const all = Object.values(got).flat().sort((a, b) => a.rating - b.rating);
    const rows = all.map(p => JSON.stringify([p.fen, p.line.join(' '), p.rating, p.themes.join(','), p.last || '']));
    fs.writeFileSync(out, `// ${all.length} chess puzzles mined from engine self-play and verified (mates with an exact solver).\n// Each: [FEN with the solver to move, solution line in UCI (solver, reply, solver, ...), estimated rating, themes, opponent's last move].\n// Generated by tools/generate-chess-puzzles.js\nwindow.CHESS_PUZZLES = [\n${rows.join(',\n')}\n];\n`);
    console.log('wrote', out, all.length, 'puzzles in', ((Date.now() - t0) / 60000).toFixed(1), 'min');
    process.exit(0);
  }
} else {
  const material = (pos, color) => { let s = 0; for (let q = 0; q < 120; q++) { if (q & 0x88) { q += 7; continue; } const p = pos.b[q]; if (p) s += (C.colorOf(p) === color ? 1 : -1) * VAL[C.typeOf(p)]; } return s; };
  const quick = pos => Engine.think(pos, { depth: 2, time: 120, noise: 0 }, ['x']).score || 0;

  // Squares of enemy pieces the piece on sq attacks (ignoring pins), after the mover's move.
  function attacksFrom(pos, sq) {
    pos.makeNull(); const caps = pos.gen([], true).filter(m => C.mFrom(m) === sq && (C.mFlags(m) & C.F_CAP)).map(m => pos.b[C.mTo(m)]); pos.unmakeNull();
    return caps;
  }
  function themesFor(pos0, line, kind) {
    const pos = new Position(pos0.fen()), themes = [], me = pos.turn;
    if (kind !== 'material') themes.push(kind);
    else themes.push('material');
    const first = pos.fromUci(line[0]);
    pos.make(first);
    const check = pos.inCheck(), cap = C.mFlags(first) & C.F_CAP;
    pos.unmake();
    if (!check && !cap) themes.push('quiet');
    // sacrifice: the first move puts a piece where it can be taken for less than it is worth
    {
      const p = pos.b[C.mFrom(first)], v = VAL[C.typeOf(p)], got = cap ? VAL[C.typeOf(pos.b[C.mTo(first)]) || 1] : 0;
      pos.make(first); const hanging = pos.attacked(C.mTo(first), me ^ 1); pos.unmake();
      if (hanging && v - got >= 200 && C.typeOf(p) !== C.K) themes.push('sacrifice');
    }
    let fork = false, promo = false;
    for (let i = 0; i < line.length; i++) {
      const m = pos.fromUci(line[i]);
      if (i % 2 === 0) {
        if (C.mFlags(m) & C.F_PROMO) promo = true;
        pos.make(m);
        const hits = attacksFrom(pos, C.mTo(m)).filter(p => C.typeOf(p) === C.K || VAL[C.typeOf(p)] >= 300);
        if (hits.length >= 2) fork = true;
      } else pos.make(m);
    }
    if (fork) themes.push('fork');
    if (promo) themes.push('promotion');
    return themes;
  }
  function rate(kind, themes, solverMoves) {
    let r = kind === 'mateIn1' ? 850 : kind === 'mateIn2' ? 1350 : kind === 'mateIn3' ? 1700 : 1050 + 250 * (solverMoves - 1);
    if (themes.includes('quiet')) r += 200;
    if (themes.includes('sacrifice')) r += 150;
    return Math.max(600, Math.min(2400, Math.round(r + (Math.random() - 0.5) * 120)));
  }

  function mateLine(pos, n) {
    const line = [];
    for (let k = n; k >= 1; k--) {
      const m = C.mateIn(pos, k, { nodes: 4e6 });
      if (!m || m === -1) return null;
      line.push(Position.uci(m)); pos.make(m);
      if (k === 1) break;
      // defender: the reply that holds out longest (ties: the engine's choice)
      let best = null, bestK = -1;
      for (const d of pos.legal()) {
        pos.make(d); let kk = 0;
        for (let j = 1; j <= k - 1; j++) { const r = C.mateIn(pos, j, { nodes: 2e6 }); if (r === -1) { kk = -9; break; } if (r) { kk = j; break; } }
        pos.unmake();
        if (kk === -9) return null;
        if (kk > bestK) { bestK = kk; best = d; }
      }
      if (!best || bestK < 1) return null;
      line.push(Position.uci(best)); pos.make(best);
    }
    return line;
  }

  const why = {}; let nrej = 0; const rej = r => { why[r] = (why[r] || 0) + 1; if (process.env.WHY && ++nrej % 40 === 0) parentPort.postMessage({ why }); return null; };
  function analyze(pos, prevForSolver, last) {
    const sm = C.scoreMoves(pos, 5);
    if (sm.length < 2) return null;
    const [b1, b2] = sm;
    if (b1.score > MATE - 20) {
      const plies = MATE - b1.score, n = (plies + 1) / 2;
      if (n > 3 || n !== Math.floor(n)) return null;
      const firsts = C.mateIn(pos, n, { nodes: 6e6 }, true);
      if (!firsts || !firsts.length) return null;
      if (n === 1 && firsts.length > 2) return null;
      if (n >= 2 && firsts.length !== 1) return null;
      // and no shorter mate exists (so "mate in n" is accurate)
      if (n > 1 && C.mateIn(pos, n - 1, { nodes: 4e6 })) return null;
      const line = mateLine(new Position(pos.fen()), n);
      if (!line) return null;
      const kind = 'mateIn' + n, themes = themesFor(pos, line, kind);
      return { kind, fen: pos.fen(), line, themes, rating: rate(kind, themes, n), last };
    }
    // winning material: one clearly best move from a roughly balanced position
    if (b1.score < 250) return rej('notWinning'); if (b1.score - b2.score < 150) return rej('notUnique'); if (prevForSolver > 150) return rej('alreadyWinning');
    const deep = C.scoreMoves(pos, 6);
    if (deep[0].move !== b1.move || deep[0].score - deep[1].score < 150 || deep[0].score < 250) return rej('deepDisagrees');
    const me = pos.turn, start = material(pos, me), p = new Position(pos.fen()), line = [];
    let mv = b1.move;
    for (let step = 0; step < 4; step++) {
      line.push(Position.uci(mv)); p.make(mv);
      if (p.status()) break;
      const gained = material(p, me) - start;
      // stop once the win is in hand: material is up and the opponent can't simply take it back
      const reply = C.scoreMoves(p, 5)[0];
      if (gained >= 200 && step > 0) break;
      if (!reply) break;
      p.make(reply.move); const after = material(p, me) - start; p.unmake();
      if (gained >= 200 && after >= 200) break;
      line.push(Position.uci(reply.move)); p.make(reply.move);
      const next = C.scoreMoves(p, 5);
      if (next.length < 2 || next[0].score - next[1].score < 150 || next[0].score < 250) { line.pop(); p.unmake(); break; }
      mv = next[0].move;
    }
    // must end on the solver's move with the material actually won
    if (line.length % 2 === 0) return rej('endsOnReply');
    const endGain = material(p, me) - start;
    if (endGain < 200 && !p.status()) return rej('noMaterialGain');
    // the opponent must not be able to win it straight back
    if (!p.status()) {
      const back = C.scoreMoves(p, 4)[0];
      if (back) { p.make(back.move); const kept = material(p, me) - start; p.unmake(); if (kept < 150) return rej('wonBack'); }
    }
    const solverMoves = (line.length + 1) / 2, themes = themesFor(pos, line, 'material');
    return { kind: 'material', fen: pos.fen(), line, themes, rating: rate('material', themes, solverMoves), last };
  }

  let seed = workerData.seed * 7919 + 12345;
  const rnd = () => { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; return ((seed >>> 0) % 1e6) / 1e6; };
  for (;;) {
    const pos = new Position(), hist = [];
    const lw = 1 + Math.floor(rnd() * 3), lb = 1 + Math.floor(rnd() * 3);
    let prevEval = 0; // from the side to move's point of view, one ply ago
    for (let ply = 0; ply < 160; ply++) {
      if (pos.status()) break;
      const e = quick(pos);
      if (ply >= 8) {
        const prevForSolver = -prevEval;
        if ((e >= 250 && prevForSolver <= 150) || e > MATE - 20) {
          const pz = analyze(pos, prevForSolver, hist[hist.length - 1]); if (!pz) rej('total');
          if (pz) parentPort.postMessage(pz);
        }
      }
      prevEval = e;
      const r = Engine.think(pos, pos.turn === 0 ? lw : lb, hist);
      if (!r.move) break;
      hist.push(Position.uci(r.move)); pos.make(r.move);
    }
  }
}
